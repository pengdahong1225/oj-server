-- ========== 题目表 ==========
CREATE TABLE IF NOT EXISTS problem
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    deleted_at    TIMESTAMP NULL DEFAULT NULL,

    title         VARCHAR(64)  NOT NULL,
    level         SMALLINT     DEFAULT 0,
    tags          JSONB,
    package_dir   VARCHAR(256) DEFAULT '',
    status        SMALLINT     DEFAULT 0,

    submit_count  INT DEFAULT 0,
    accept_count  INT DEFAULT 0,
    comment_count INT DEFAULT 0,

    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_title ON problem (title);
CREATE INDEX IF NOT EXISTS idx_problem_deleted_at ON problem (deleted_at);
CREATE INDEX IF NOT EXISTS idx_status ON problem (status);

CREATE TRIGGER trg_problem_updated
    BEFORE UPDATE ON problem
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ========== 告示表 ==========
CREATE TABLE IF NOT EXISTS notice
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL DEFAULT NULL,

    title      VARCHAR(64) NOT NULL,
    content    TEXT        NOT NULL,
    create_by  BIGINT      DEFAULT 0,
    status     SMALLINT    DEFAULT 0,

    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_status_create ON notice (status, created_at);
CREATE INDEX IF NOT EXISTS idx_notice_deleted_at ON notice (deleted_at);

CREATE TRIGGER trg_notice_updated
    BEFORE UPDATE ON notice
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ========== 评论表 ==========
CREATE TABLE IF NOT EXISTS comment
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    deleted_at       TIMESTAMP NULL DEFAULT NULL,

    obj_id           BIGINT       NOT NULL,
    user_id          BIGINT       NOT NULL,
    user_name        VARCHAR(64)  DEFAULT '',
    user_avatar_url  VARCHAR(256) DEFAULT '',
    content          TEXT         NOT NULL,
    status           SMALLINT     DEFAULT 1,
    reply_count      INT          DEFAULT 0,
    like_count       INT          DEFAULT 0,
    child_count      INT          DEFAULT 0,
    pub_stamp        BIGINT       NOT NULL,
    pub_region       VARCHAR(64)  DEFAULT '',

    is_root          SMALLINT     DEFAULT 1,
    root_id          BIGINT       NOT NULL,
    root_comment_id  BIGINT       NOT NULL,
    reply_id         BIGINT       NOT NULL,
    reply_comment_id BIGINT       NOT NULL,
    reply_user_name  VARCHAR(64)  DEFAULT '',

    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_obj_id ON comment (obj_id);
CREATE INDEX IF NOT EXISTS idx_user_id ON comment (user_id);
CREATE INDEX IF NOT EXISTS idx_root_id ON comment (root_id);
CREATE INDEX IF NOT EXISTS idx_reply_id ON comment (reply_id);
CREATE INDEX IF NOT EXISTS idx_like_count ON comment (like_count);
CREATE INDEX IF NOT EXISTS idx_comment_deleted_at ON comment (deleted_at);
CREATE INDEX IF NOT EXISTS idx_obj_status_like ON comment (obj_id, status, like_count);
CREATE INDEX IF NOT EXISTS idx_obj_status_stamp ON comment (obj_id, status, pub_stamp);

CREATE TRIGGER trg_comment_updated
    BEFORE UPDATE ON comment
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ========== 用户提交记录表 ==========
CREATE TABLE IF NOT EXISTS user_submit_record
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    uid          BIGINT       NOT NULL,
    user_name    VARCHAR(64)  NOT NULL,
    problem_id   BIGINT       NOT NULL,
    problem_name VARCHAR(64)  NOT NULL,

    lang         VARCHAR(64)  DEFAULT '',
    code         TEXT         NOT NULL,

    status       SMALLINT     DEFAULT 0,
    accepted     BOOLEAN      DEFAULT FALSE,
    message      VARCHAR(256) DEFAULT '',
    result       BYTEA        NOT NULL,

    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_uid_created ON user_submit_record (uid, created_at);
CREATE INDEX IF NOT EXISTS idx_problem_created ON user_submit_record (problem_id, created_at);
CREATE INDEX IF NOT EXISTS idx_uid_problem_created ON user_submit_record (uid, problem_id, created_at);

CREATE TRIGGER trg_submit_record_updated
    BEFORE UPDATE ON user_submit_record
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

