-- ========== 通用触发器函数：自动更新 updated_at ==========
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ========== 用户信息表 ==========
CREATE TABLE IF NOT EXISTS user_info
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL DEFAULT NULL,

    mobile     BIGINT       NOT NULL,
    password   VARCHAR(256) NOT NULL,
    username   VARCHAR(64)  DEFAULT '新用户',
    email      VARCHAR(64)  DEFAULT '',
    role       SMALLINT     DEFAULT 0,
    avatar_url VARCHAR(256) DEFAULT '',

    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_mobile ON user_info (mobile);
CREATE INDEX IF NOT EXISTS idx_user_info_deleted_at ON user_info (deleted_at);

CREATE TRIGGER trg_user_info_updated
    BEFORE UPDATE ON user_info
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

